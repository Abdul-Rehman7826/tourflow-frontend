// 10. SEED ALL DEMO DATA TO LOCAL STORAGE
// ============================================================================
export function seedAllDemoData(tenantId = PRIMARY_DEMO_TENANT_ID, force = false): void {
  if (typeof window === "undefined") return;

  const employeeKey = `tourflow_hr_employees_${tenantId}`;
  const shiftKey = `tourflow_hr_shifts_${tenantId}`;
  const attendanceKey = `tourflow_attendance_${tenantId}`;
  const leaveKey = `tourflow_leave_${tenantId}`;
  const payrollKey = `tourflow_payroll_${tenantId}`;
  const advanceKey = `tourflow_salary_advances_${tenantId}`;
  const erpKey = "tourflow_erp_v3";

  // 1. Employees
  if (force || !localStorage.getItem(employeeKey)) {
    const scopedEmployees = DEMO_EMPLOYEES.map((e) => ({ ...e, tenantId }));
    localStorage.setItem(employeeKey, JSON.stringify(scopedEmployees));
  }

  // 2. Shifts
  if (force || !localStorage.getItem(shiftKey)) {
    localStorage.setItem(shiftKey, JSON.stringify(DEMO_SHIFTS));
  }

  // 3. Attendance
  if (force || !localStorage.getItem(attendanceKey)) {
    const today = localDateKey();
    const records = createDemoTodayAttendance(today).map((r) => ({ ...r, tenantId }));
    localStorage.setItem(attendanceKey, JSON.stringify(records));
  }

  // 4. Leave
  if (force || !localStorage.getItem(leaveKey)) {
    const scopedLeaves = DEMO_LEAVE_REQUESTS.map((l) => ({ ...l, tenantId }));
    localStorage.setItem(leaveKey, JSON.stringify(scopedLeaves));
  }

  // 5. Payroll
  if (force || !localStorage.getItem(payrollKey)) {
    const scopedPayroll = DEMO_PAYROLL_RUNS.map((p) => ({ ...p, tenantId }));
    localStorage.setItem(payrollKey, JSON.stringify(scopedPayroll));
  }

  // 6. Salary Advances
  if (force || !localStorage.getItem(advanceKey)) {
    const scopedAdvances = DEMO_SALARY_ADVANCES.map((a) => ({ ...a, tenantId }));
    localStorage.setItem(advanceKey, JSON.stringify(scopedAdvances));
  }

  // 7. ERP State (Suppliers, Office Expenses, Vault)
  try {
    const existingRaw = localStorage.getItem(erpKey);
    const existing = existingRaw ? JSON.parse(existingRaw) : {};
    const scopedSuppliers = DEMO_SUPPLIERS.map((s) => ({ ...s, tenantId }));
    const scopedOfficeExpenses = DEMO_OFFICE_EXPENSES.map((o) => ({ ...o, tenantId }));
    const scopedVaultDocs = DEMO_VAULT_DOCUMENTS.map((v) => ({ ...v, tenantId }));

    const updated = {
      ...existing,
      suppliers: force || !existing.suppliers || existing.suppliers.length === 0
        ? scopedSuppliers
        : existing.suppliers,
      officeExpenses: force || !existing.officeExpenses || existing.officeExpenses.length === 0
        ? scopedOfficeExpenses
        : existing.officeExpenses,
      vaultDocuments: force || !existing.vaultDocuments || existing.vaultDocuments.length === 0
        ? scopedVaultDocs
        : existing.vaultDocuments,
    };
    localStorage.setItem(erpKey, JSON.stringify(updated));
  } catch (err) {
    console.warn("Error updating demo ERP state:", err);
  }
}
